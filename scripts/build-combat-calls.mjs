import {spawnSync} from 'node:child_process';
import {mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const sources={male:[[0,.39],[2.04,2.39],[4.52,4.94],[6.99,7.64],[9.22,10.02],[11.72,12.34],[14.19,14.70]],female:[[0,.47],[2.99,3.38],[5.76,6.35],[8.96,9.77],[12.12,13.17],[14.62,15.05],[17.65,18.32]]};
const rate=22050,manifest={};
await mkdir(path.join(root,'public/assets/audio/combat'),{recursive:true});
for(const [bank,spans] of Object.entries(sources)){
 let cursor=0;const pieces=[],clips=[];
 for(const [i,[start,end]] of spans.entries()){
  const tempo=i<3?1.35:i===3?1.4:i===4?1.25:1.5;
  const run=spawnSync('ffmpeg',['-v','error','-i',path.join(root,`art-source/audio/combat-calls/${bank}.mp3`),'-af',`atrim=start=${start}:end=${end},asetpts=PTS-STARTPTS,atempo=${tempo}`,'-ac','1','-ar',String(rate),'-f','s16le','pipe:1'],{maxBuffer:4e6});
  if(run.status!==0)throw Error(run.stderr.toString());
  const samples=run.stdout.length/2,out=Buffer.alloc(run.stdout.length);let peak=1;
  if(samples<rate*.08)throw Error(`Empty or truncated combat call: ${bank} ${i}`);
  for(let j=0;j<samples;j++)peak=Math.max(peak,Math.abs(run.stdout.readInt16LE(j*2)));
  for(let j=0;j<samples;j++){const fade=Math.min(1,j/(rate*.005),(samples-1-j)/(rate*.018));out.writeInt16LE(Math.round(run.stdout.readInt16LE(j*2)/peak*24000*fade),j*2);}
  clips.push([cursor/rate,samples/rate]);pieces.push(out);cursor+=samples;
 }
 const data=Buffer.concat(pieces),header=Buffer.alloc(44);header.write('RIFF');header.writeUInt32LE(36+data.length,4);header.write('WAVEfmt ',8);header.writeUInt32LE(16,16);header.writeUInt16LE(1,20);header.writeUInt16LE(1,22);header.writeUInt32LE(rate,24);header.writeUInt32LE(rate*2,28);header.writeUInt16LE(2,32);header.writeUInt16LE(16,34);header.write('data',36);header.writeUInt32LE(data.length,40);
 await writeFile(path.join(root,`public/assets/audio/combat/${bank}-v1.wav`),Buffer.concat([header,data]));manifest[bank]=clips;
}
await writeFile(path.join(root,'game/combat-call-clips.ts'),'// Generated by scripts/build-combat-calls.mjs. Start/duration in seconds.\nexport const COMBAT_CALL_CLIPS='+JSON.stringify(manifest,null,2)+' as const;\n');
console.log(manifest);
